const tables: Record<Locale, Record<MessageKey, string>> = { en, 'zh-cn': zhCn };

let resolver: () => Locale = () => 'en';

/** The host decides the locale (VS Code config + display language); tests and tools set it directly. */
export function setLocaleResolver(fn: () => Locale): void {
  resolver = fn;
}

export function currentLocale(): Locale {
  return resolver();
}

/** Format a message in the active locale; {0}, {1}... are replaced by args. */
export function t(key: MessageKey, ...args: Array<string | number>): string {
  const s = tables[currentLocale()][key] ?? en[key];
  return s.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}

export function kindLabel(kind: SymbolKind): string {
  return t(`kind_${kind}` as MessageKey);
}

export function kindWord(kind: SymbolKind): string {
  return t(`kind1_${kind}` as MessageKey);
}

/** Strings the Relations webview needs; sent once per page load. */
export function relationStrings(): Record<string, string> {
  const keys: MessageKey[] = ['noRelations', 'nothingToShow', 'truncated', 'nodesEdges', 'expandMore', 'collapse', 'listCallers', 'listCallees'];
  return Object.fromEntries(keys.map((k) => [k, tables[currentLocale()][k]]));
}
